def assert_writable_target(path: Path, *, force: bool) -> None:
    if path.exists():
        if path.is_symlink():
            raise AcceptanceEnvError(f"refusing to write through symlink: {path}")
        if not path.is_file():
            raise AcceptanceEnvError(f"refusing to overwrite non-regular file: {path}")
        if not force:
            raise AcceptanceEnvError(f"{path} already exists; rerun with --force after preserving operator edits")
    current = path.parent
    while current != current.parent:
        if current.exists() and current.is_symlink():
            raise AcceptanceEnvError(f"refusing to write inside symlinked directory: {current}")
        current = current.parent


def write_private_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        tmp_path.chmod(0o640)
        os.replace(tmp_path, path)
        path.chmod(0o640)
    finally:
        if tmp_path.exists():
            tmp_path.unlink()


def generate_acceptance_env(config: AcceptanceEnvConfig) -> dict[str, Any]:
    output = config.output or default_output_path(config.data_root)
    output = output if output.is_absolute() else Path.cwd() / output
    existed = output.exists()
    assert_writable_target(output, force=config.force)
    content = render_acceptance_env(config)
    write_private_text(output, content)
    return {
        "output": str(output),
        "data_root": str(config.data_root),
        "created": not existed,
        "bytes": len(content.encode("utf-8")),
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate a sourceable B1 AI Hub live-acceptance environment file.")
    parser.add_argument("--data-root", "--root", dest="data_root", default=os.getenv("B1_DATA_ROOT", DEFAULT_DATA_ROOT))
    parser.add_argument("--output", default="", help="File to create. Defaults to $B1_BACKUP_ROOT/acceptance/operator-live-acceptance.env.")
    parser.add_argument("--host-api", default=os.getenv("B1_HOST_API", DEFAULT_HOSTS["api"]))
    parser.add_argument("--host-comfy", default=os.getenv("B1_HOST_COMFY", DEFAULT_HOSTS["comfy"]))
    parser.add_argument("--host-voice", default=os.getenv("B1_HOST_VOICE", DEFAULT_HOSTS["voice"]))
    parser.add_argument("--host-models", default=os.getenv("B1_HOST_MODELS", DEFAULT_HOSTS["models"]))
    parser.add_argument("--legacy-comfy-host", default=os.getenv("B1_LEGACY_COMFY_HOST", DEFAULT_HOSTS["legacy_comfy"]))
    parser.add_argument("--force", action="store_true", help="Overwrite an existing generated file after preserving operator edits.")
    parser.add_argument("--print", action="store_true", dest="print_only", help="Print to stdout instead of writing a file.")
    return parser.parse_args()


def config_from_args(args: argparse.Namespace) -> AcceptanceEnvConfig:
    data_root = Path(str(args.data_root)).expanduser()
    output = Path(str(args.output)).expanduser() if str(args.output).strip() else None
    return AcceptanceEnvConfig(
        data_root=data_root,
        output=output,
        host_api=str(args.host_api).strip() or DEFAULT_HOSTS["api"],
        host_comfy=str(args.host_comfy).strip() or DEFAULT_HOSTS["comfy"],
        host_voice=str(args.host_voice).strip() or DEFAULT_HOSTS["voice"],
        host_models=str(args.host_models).strip() or DEFAULT_HOSTS["models"],
        legacy_comfy_host=str(args.legacy_comfy_host).strip() or DEFAULT_HOSTS["legacy_comfy"],
        force=bool(args.force),
    )


def main() -> None:
    args = parse_args()
    config = config_from_args(args)
    if args.print_only:
        print(render_acceptance_env(config), end="")
        return
    result = generate_acceptance_env(config)
    print(f"created {result['output']}")
    print("review it, set the blank operator-supplied values, then source it before running make operator-live-acceptance")


if __name__ == "__main__":
    main()
