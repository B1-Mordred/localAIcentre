def default_output_path(data_root: Path) -> Path:
    backup_root = Path(os.getenv("B1_BACKUP_ROOT", str(data_root / "backups")))
    return backup_root / "acceptance" / "operator-live-acceptance.env"


def shell_default_literal(key: str, value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`")
    return f'export {key}="${{{key}:-{escaped}}}"'


def shell_assign_literal(key: str, value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`")
    return f'export {key}="{escaped}"'


def shell_default_expression(key: str, expression: str) -> str:
    return f'export {key}="${{{key}:-{expression}}}"'


def section(title: str) -> list[str]:
    return ["", f"# {title}"]


